def params(t):
    """Temperature + infusion count + the steep-time strip (the component shelved from the home page)."""
    cells = "".join(f'<div><span class="label">{"Промивка" if k == 0 else f"Настій {k}"}</span><b>{esc(s)}</b></div>'
                    for k, s in enumerate(t["steeps"]))
    return (f'<div class="brew"><div class="brew-head"><div><span class="label">Вода</span><b class="num">{esc(t["temp"])}</b></div>'
            f'<div><span class="label">Проливів</span><b class="num">{esc(t["infusions"])}</b></div></div>'
            f'<div class="steeps" aria-label="Час заварювання">{cells}</div></div>')


def body(t):
    ex = f'<p class="tea-ex"><span class="label">Приклад</span> {esc(t["example"])}</p>' if t.get("example") else ""
    return f'<p>{esc(t["text"])}</p>{ex}'


def tea(n, t):
    head = f'<span class="n">{n:02d}</span><div class="tea-title"><h2>{esc(t["name"])}</h2><span class="label">{esc(t["tag"])}</span></div>'
    if "variants" not in t:
        return f'<article class="tea reveal">{head}<div class="tea-copy">{body(t)}</div>{params(t)}</article>'
    subs = "".join(f'<div class="variant"><div class="tea-copy"><h3>{esc(v["name"])}</h3>{body(v)}</div>{params(v)}</div>' for v in t["variants"])
    return f'<article class="tea has-variants reveal">{head}<div class="tea-copy">{body(t)}</div>{subs}</article>'


