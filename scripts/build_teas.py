#!/usr/bin/env python3
"""Build the reference pages:
  vydy-chaiu.html  tea kinds, from Content/drafts/teas.json
  voda.html        water for tea, from Content/drafts/water.json
then print each to assets/<name>.pdf with headless Google Chrome (skipped if Chrome is missing).
Run from the repo root: python3 scripts/build_teas.py"""
import json
import subprocess
from html import escape as esc
from pathlib import Path

