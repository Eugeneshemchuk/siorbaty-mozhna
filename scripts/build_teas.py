def actions(pdf, name, lesson):
    return (f'<div class="teas-actions"><a class="cta" href="{pdf}" download="Сьорбати Можна · {name}.pdf">Завантажити PDF {DOWN}</a>'
            f'<a class="cta ghost" href="module.html#{lesson.replace(".", "-").zfill(4)}">Урок {lesson} {ARROW}</a></div>')


def back(lesson, title):
    return (f'<a class="next" href="module.html#{lesson.replace(".", "-").zfill(4)}"><span class="leafband" aria-hidden="true"></span>'
            f'<div><span class="label">Повернутися до уроку</span><h3>{title}</h3></div>{ARROW}</a>')


